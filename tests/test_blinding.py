"""Guards the de-identification ordering fix (audit P1-4): full model ids must be
stripped before vendor stems, or the stem replacement inside a longer id breaks the
exact match and leaks the version suffix ("[model]-3.1-pro-preview")."""
from __future__ import annotations

import json

from src.eval.blinding import _build_strip_patterns, _strip_identifying_tokens


def _make_reports_dir(tmp_path):
    d = tmp_path / "reports"
    d.mkdir()
    for provider, model in [
        ("anthropic", "claude-opus-5"),
        ("openai", "gpt-6-astra"),
        ("gemini", "gemini-3.1-pro-preview"),
    ]:
        (d / f"Sub01_P__{provider}__{model}__v1.json").write_text(
            json.dumps({"subject_id": "Sub01", "provider": provider, "model": model, "report_text": "x"})
        )
    return d


def test_full_model_ids_leave_no_version_fragments(tmp_path):
    patterns = _build_strip_patterns(_make_reports_dir(tmp_path))
    text = (
        "Generated by gemini-3.1-pro-preview, compared against claude-opus-5 "
        "and gpt-6-astra, also plain gemini and openai mentions."
    )
    result = _strip_identifying_tokens(text, patterns)
    for fragment in ["3.1-pro-preview", "opus-5", "6-astra", "gemini", "claude", "gpt", "openai"]:
        assert fragment.lower() not in result.lower(), f"leaked: {fragment} in {result!r}"


def test_vendor_stems_still_caught_without_full_id(tmp_path):
    patterns = _build_strip_patterns(_make_reports_dir(tmp_path))
    result = _strip_identifying_tokens("As an Anthropic model, Claude notes...", patterns)
    assert "anthropic" not in result.lower()
    assert "claude" not in result.lower()
